package com.sievex.app

import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.util.concurrent.atomic.AtomicLong

/** One follow-up spoken or typed thought appended to an existing note thread. */
data class NoteFollowUp(
    val text: String,
    val whenText: String,
    val createdAt: Long = System.currentTimeMillis(),
    val audioPath: String? = null
)

data class StoredNote(
    val id: Long,
    val title: String,
    val oneLine: String,
    val mode: String,
    val whenText: String,
    val verbatim: String,
    val why: String,
    val question: String,
    val tags: List<String>,
    val audioPath: String?,
    /** The space this note is filed under, or null for "no space". Never changes other fields. */
    val spaceId: String? = null,
    /**
     * When the user last edited this note by hand, or null if they never have. Only
     * [NoteStore.update] may set it, so its presence means "this note is the user's words now",
     * which is what the editor badge reads.
     */
    val editedAt: Long? = null,
    /** How the note was shaped; see [NoteFormat]. Defaults keep older files readable. */
    val format: String = NoteFormat.NOTE.id,
    /** The bullet or step list a LIST/STEPS note carries; empty for every other format. */
    val items: List<String> = emptyList(),
    /** Epoch millis when the note was created; migrated descending for legacy notes. */
    val createdAt: Long = 0L,
    /** Epoch millis when an Action note was marked done, or null when open/pending. */
    val completedAt: Long? = null,
    /** Chronological follow-up voice/text entries appended to this note thread. */
    val followUps: List<NoteFollowUp> = emptyList(),
    /** Accepted/curated open questions; [question] mirrors the first entry for legacy callers. */
    val openQuestions: List<String> = emptyList(),
    /** Candidate open questions generated by the LLM awaiting Keep / Discard triage. */
    val questionDrafts: List<String> = emptyList(),
    /** Zero-based step indices marked done on a [NoteFormat.STEPS] note. */
    val completedSteps: Set<Int> = emptySet()
) {
    fun resolvedOpenQuestions(): List<String> =
        if (openQuestions.isNotEmpty()) openQuestions
        else listOfNotNull(question.trim().takeIf { it.isNotEmpty() })
}

/** Flat JSON persistence. Enough until the Markdown filing layer lands. */
object NoteStore {

    private val notes = mutableListOf<StoredNote>()
    private val byIdMap = HashMap<Long, StoredNote>()
    private val audioPaths = HashSet<String>()
    private var file: File? = null

    private val _version = MutableStateFlow(0L)
    val version: StateFlow<Long> = _version.asStateFlow()

    /**
     * Note ids, seeded past the highest id already on disk. Capture timestamps are not unique
     * enough (two bursts can land in the same millisecond, and a clock can move backwards).
     */
    private val ids = AtomicLong(0)

    /**
     * Set when a bad file could not be moved aside. Saving would then overwrite the only copy
     * of the user's notes with an empty array, so writes stay off until the process restarts.
     */
    @Volatile
    private var writesBlocked = false

    fun nextId(): Long = ids.incrementAndGet()

    fun init(root: File) {
        synchronized(this) {
            if (file != null) return
            file = File(root, "notes.json")
            load()
        }
        // Same root, same process: whoever sets notes up also gets spaces, lenses and the job
        // queue. Deliberately outside the lock above so the stores never lock each other backwards.
        // Every init is idempotent, so a caller that inits one of them directly is harmless.
        SpaceStore.init(root)
        LensStore.init(root)
        JobQueue.init(root)
        MediaStore.init(root)
        ReminderStore.init(root)
        // Dangling space links can only be detected once spaces.json is in memory, so this is
        // after SpaceStore.init and never inside load().
        repairSpaceLinks()
        _version.value = _version.value + 1L
    }

    @Synchronized
    fun all(): List<StoredNote> = notes.toList()

    @Synchronized
    fun byId(noteId: Long): StoredNote? = byIdMap[noteId]

    @Synchronized
    fun hasAudioPath(wavPath: String): Boolean = wavPath in audioPaths

    @Synchronized
    fun inSpace(spaceId: String): List<StoredNote> = notes.filter { it.spaceId == spaceId }

    private fun rebuildIndexes() {
        byIdMap.clear()
        audioPaths.clear()
        for (n in notes) {
            byIdMap[n.id] = n
            n.audioPath?.let { audioPaths.add(it) }
            n.followUps.forEach { f -> f.audioPath?.let { audioPaths.add(it) } }
        }
    }

    /**
     * Files one note under a space, or detaches it with null. Only `spaceId` is written;
     * every other field is copied through untouched.
     */
    @Synchronized
    fun assignSpace(noteId: Long, spaceId: String?) {
        val i = notes.indexOfFirst { it.id == noteId }
        if (i < 0) {
            CaptureLog.add("notes: assignSpace, unknown note $noteId")
            return
        }
        if (notes[i].spaceId == spaceId) return
        val updated = notes[i].copy(spaceId = spaceId)
        notes[i] = updated
        byIdMap[updated.id] = updated
        save()
    }

    @Synchronized
    fun setCompleted(noteId: Long, completed: Boolean) {
        val i = notes.indexOfFirst { it.id == noteId }
        if (i < 0) return
        val next = if (completed) System.currentTimeMillis() else null
        if ((notes[i].completedAt != null) == completed) return
        val updated = notes[i].copy(completedAt = next)
        notes[i] = updated
        byIdMap[updated.id] = updated
        save()
        CaptureLog.add("notes: ${if (completed) "completed" else "reopened"} $noteId")
    }

    /** Toggles completion of one step index on a [NoteFormat.STEPS] note. */
    @Synchronized
    fun toggleStepCompleted(noteId: Long, index: Int) {
        val i = notes.indexOfFirst { it.id == noteId }
        if (i < 0) return
        val existing = notes[i]
        if (index !in existing.items.indices) return
        val next = if (index in existing.completedSteps) {
            existing.completedSteps - index
        } else {
            existing.completedSteps + index
        }
        val updated = existing.copy(completedSteps = next)
        notes[i] = updated
        byIdMap[updated.id] = updated
        save()
        CaptureLog.add("notes: toggled step $index on $noteId")
    }

    /** Appends a follow-up entry to an existing note thread. Returns null if the note no longer exists. */
    @Synchronized
    fun appendFollowUp(noteId: Long, entry: NoteFollowUp): StoredNote? {
        val i = notes.indexOfFirst { it.id == noteId }
        if (i < 0) return null
        val updated = notes[i].copy(followUps = notes[i].followUps + entry)
        notes[i] = updated
        byIdMap[updated.id] = updated
        entry.audioPath?.let { audioPaths.add(it) }
        save()
        CaptureLog.add("notes: appended follow-up to $noteId (${updated.followUps.size} total)")
        return updated
    }

    /** Marks a note's open question(s) as answered/resolved. Null clears all open questions. */
    @Synchronized
    fun resolveOpenQuestion(noteId: Long, questionText: String? = null) {
        val i = notes.indexOfFirst { it.id == noteId }
        if (i < 0) return
        val existing = notes[i]
        val currentOpen = existing.resolvedOpenQuestions()
        if (currentOpen.isEmpty() && existing.question.isBlank()) return

        val remaining = if (questionText == null) {
            emptyList()
        } else {
            val target = questionText.trim()
            currentOpen.filterNot { it.equals(target, ignoreCase = true) }
        }
        val nextQuestion = remaining.firstOrNull() ?: ""
        if (remaining == existing.openQuestions && nextQuestion == existing.question) return
        val updated = existing.copy(question = nextQuestion, openQuestions = remaining)
        notes[i] = updated
        byIdMap[updated.id] = updated
        save()
        CaptureLog.add("notes: resolved open question on $noteId")
    }

    /** Marks all open questions on a note as resolved. */
    @Synchronized
    fun clearOpenQuestion(noteId: Long) = resolveOpenQuestion(noteId, null)

    /** Promotes one candidate draft question into accepted open questions. */
    @Synchronized
    fun acceptQuestionDraft(noteId: Long, draft: String) {
        val i = notes.indexOfFirst { it.id == noteId }
        if (i < 0) return
        val clean = draft.trim()
        if (clean.isEmpty()) return
        val existing = notes[i]
        val remainingDrafts = existing.questionDrafts.filterNot { it.equals(clean, ignoreCase = true) }
        val currentOpen = existing.resolvedOpenQuestions()
        val nextOpen = if (currentOpen.any { it.equals(clean, ignoreCase = true) }) {
            currentOpen
        } else {
            currentOpen + clean
        }
        val nextQuestion = nextOpen.firstOrNull() ?: ""
        val updated = existing.copy(
            question = nextQuestion,
            openQuestions = nextOpen,
            questionDrafts = remainingDrafts
        )
        if (updated == existing) return
        notes[i] = updated
        byIdMap[updated.id] = updated
        save()
        CaptureLog.add("notes: accepted question draft on $noteId")
    }

    /** Removes one candidate draft question without accepting it. */
    @Synchronized
    fun discardQuestionDraft(noteId: Long, draft: String) {
        val i = notes.indexOfFirst { it.id == noteId }
        if (i < 0) return
        val clean = draft.trim()
        val existing = notes[i]
        val remainingDrafts = existing.questionDrafts.filterNot { it.equals(clean, ignoreCase = true) }
        if (remainingDrafts.size == existing.questionDrafts.size) return
        val updated = existing.copy(questionDrafts = remainingDrafts)
        notes[i] = updated
        byIdMap[updated.id] = updated
        save()
        CaptureLog.add("notes: discarded question draft on $noteId")
    }

    /** Clears all pending candidate draft questions on a note. */
    @Synchronized
    fun discardAllQuestionDrafts(noteId: Long) {
        val i = notes.indexOfFirst { it.id == noteId }
        if (i < 0) return
        val existing = notes[i]
        if (existing.questionDrafts.isEmpty()) return
        val updated = existing.copy(questionDrafts = emptyList())
        notes[i] = updated
        byIdMap[updated.id] = updated
        save()
        CaptureLog.add("notes: discarded all question drafts on $noteId")
    }

    /**
     * Permanently removes a note, detaches it from linked media items, and deletes any unshared
     * recording file on disk.
     */
    @Synchronized
    fun delete(noteId: Long): StoredNote? {
        val i = notes.indexOfFirst { it.id == noteId }
        if (i < 0) return null
        val removed = notes.removeAt(i)
        byIdMap.remove(noteId)
        val candidateAudio = buildList {
            removed.audioPath?.let { add(it) }
            removed.followUps.forEach { f -> f.audioPath?.let { add(it) } }
        }.distinct()
        for (audio in candidateAudio) {
            val stillUsed = notes.any { n ->
                n.audioPath == audio || n.followUps.any { it.audioPath == audio }
            }
            if (!stillUsed) {
                audioPaths.remove(audio)
                runCatching {
                    val wav = File(audio)
                    if (wav.isFile) wav.delete()
                }
            }
        }
        MediaStore.unlinkNote(noteId)
        ReminderStore.cancelForTarget(null, ReminderTargetType.NOTE, noteId.toString())
        save()
        CaptureLog.add("notes: deleted $noteId")
        return removed
    }

    /**
     * Detaches every note filed under a space in one pass and one save. Called by
     * `SpaceStore.delete` before the space itself is removed, so a crash cannot leave
     * notes pointing at a space that no longer exists.
     */
    @Synchronized
    fun clearSpace(spaceId: String) {
        var detached = 0
        for (i in notes.indices) {
            if (notes[i].spaceId == spaceId) {
                val updated = notes[i].copy(spaceId = null)
                notes[i] = updated
                byIdMap[updated.id] = updated
                detached++
            }
        }
        if (detached == 0) return
        save()
        CaptureLog.add("notes: detached $detached note(s) from $spaceId")
    }

    @Synchronized
    fun add(note: StoredNote) {
        val normalizedOpen = note.resolvedOpenQuestions()
        val normalizedQuestion = normalizedOpen.firstOrNull() ?: ""
        val stamped = note.copy(
            createdAt = if (note.createdAt > 0L) note.createdAt else System.currentTimeMillis(),
            question = normalizedQuestion,
            openQuestions = normalizedOpen,
            questionDrafts = note.questionDrafts.map { it.trim() }.filter { it.isNotEmpty() }.distinct()
        )
        notes.add(0, stamped)
        byIdMap[stamped.id] = stamped
        stamped.audioPath?.let { audioPaths.add(it) }
        save()
    }

    /**
     * Replaces one note with a user-edited copy of itself and stamps [StoredNote.editedAt].
     *
     * This is the **only** writer of note content: capture, filing and the lens code never call
     * it. [StoredNote.id] and [StoredNote.audioPath] are not content, so they always keep the
     * stored value — an edit can never detach a recording or rename a note out of existence. The
     * space link is likewise owned by [assignSpace] only, so a stale editor cannot undo a move.
     * Returns the note as saved, or null when [note]'s id is not in the store.
     */
    @Synchronized
    fun update(note: StoredNote): StoredNote? = write(note, markEdited = true)

    /**
     * Replaces the AI-shaped content of a note without pretending the user edited it.
     *
     * Used by reanalysis: the title, summary, insight and tags are the model's work, so stamping
     * [StoredNote.editedAt] would light up the "your words now" badge for text nobody wrote. The
     * stored stamp (and the audio, the space and the id) is kept as it was.
     */
    fun replaceWithAi(note: StoredNote): StoredNote? = write(note, markEdited = false)

    /**
     * The one writer of note content. Synchronised because reanalysis runs on an IO thread while
     * the UI poll reads [all] and the queue worker may [add]: without the monitor, `save()` could
     * iterate the list while it is being replaced.
     */
    @Synchronized
    private fun write(note: StoredNote, markEdited: Boolean): StoredNote? {
        val i = notes.indexOfFirst { it.id == note.id }
        if (i < 0) {
            CaptureLog.add("notes: update, unknown note ${note.id}")
            return null
        }
        val existing = notes[i]
        val cleanDrafts = note.questionDrafts.map { it.trim() }.filter { it.isNotEmpty() }.distinct()
        val syncedOpen = if (!markEdited) {
            // Reanalysis refreshes questionDrafts while preserving any user-curated open questions.
            existing.resolvedOpenQuestions()
        } else {
            val candidate = note.openQuestions.map { it.trim() }.filter { it.isNotEmpty() }.distinct()
            if (candidate.isNotEmpty()) {
                candidate
            } else {
                val legacy = note.question.trim()
                if (legacy.isNotEmpty()) listOf(legacy) else emptyList()
            }
        }
        val syncedQuestion = syncedOpen.firstOrNull() ?: ""
        val syncedCompletedSteps = if (note.items == existing.items) {
            existing.completedSteps.filterTo(LinkedHashSet()) { it in note.items.indices }
        } else {
            emptySet()
        }
        val edited = note.copy(
            audioPath = existing.audioPath,
            spaceId = existing.spaceId,
            editedAt = if (markEdited) System.currentTimeMillis() else existing.editedAt,
            createdAt = existing.createdAt,
            completedAt = existing.completedAt,
            followUps = existing.followUps,
            question = syncedQuestion,
            openQuestions = syncedOpen,
            questionDrafts = cleanDrafts,
            completedSteps = syncedCompletedSteps
        )
        notes[i] = edited
        byIdMap[edited.id] = edited
        save()
        CaptureLog.add("notes: edited ${edited.id}")
        return edited
    }

    /**
     * A space id on disk that no longer exists is the same as no space, e.g. after a crash
     * between `clearSpace` and the space removal. Repairs silently, one save.
     */
    private fun repairSpaceLinks() {
        if (SpaceStore.loadBroken()) {
            // An unreadable spaces.json looks exactly like "every space is gone"; repairing
            // here would strip every note's space because of a broken read.
            CaptureLog.add("notes: skipping space repair, spaces.json did not load")
            return
        }
        val live = SpaceStore.all().map { it.id }.toSet()
        synchronized(this) {
            var repaired = 0
            for (i in notes.indices) {
                val spaceId = notes[i].spaceId ?: continue
                if (spaceId !in live) {
                    val updated = notes[i].copy(spaceId = null)
                    notes[i] = updated
                    byIdMap[updated.id] = updated
                    repaired++
                }
            }
            if (repaired == 0) return
            save()
            CaptureLog.add("notes: unassigned $repaired note(s) from missing space(s)")
        }
    }

    private fun load() {
        val f = file ?: return
        if (!f.exists()) return

        // Parse into a scratch list: a failure half-way through must not leave a partial
        // in-memory list that the next save would persist over the real one.
        val parsed = runCatching {
            val arr = JSONArray(f.readText())
            val loaded = mutableListOf<StoredNote>()
            for (i in 0 until arr.length()) {
                val o = arr.getJSONObject(i)
                val tags = mutableListOf<String>()
                val ta = o.optJSONArray("tags")
                if (ta != null) for (j in 0 until ta.length()) tags.add(ta.getString(j))
                val items = mutableListOf<String>()
                val ia = o.optJSONArray("items")
                if (ia != null) for (j in 0 until ia.length()) items.add(ia.getString(j))
                val followUps = mutableListOf<NoteFollowUp>()
                val fa = o.optJSONArray("followUps")
                if (fa != null) {
                    for (j in 0 until fa.length()) {
                        val fo = fa.optJSONObject(j) ?: continue
                        val ft = fo.optString("text")
                        if (ft.isBlank()) continue
                        followUps.add(
                            NoteFollowUp(
                                text = ft,
                                whenText = fo.optString("whenText"),
                                createdAt = fo.optLong("createdAt", 0L),
                                audioPath = fo.optString("audioPath").ifBlank { null }
                            )
                        )
                    }
                }
                val legacyQuestion = o.optString("question").trim()
                val openQuestions = mutableListOf<String>()
                if (o.has("openQuestions")) {
                    val oq = o.optJSONArray("openQuestions")
                    if (oq != null) {
                        for (j in 0 until oq.length()) {
                            val q = oq.optString(j).trim()
                            if (q.isNotEmpty()) openQuestions.add(q)
                        }
                    }
                } else if (legacyQuestion.isNotEmpty()) {
                    openQuestions.add(legacyQuestion)
                }
                val questionDrafts = mutableListOf<String>()
                val qd = o.optJSONArray("questionDrafts")
                if (qd != null) {
                    for (j in 0 until qd.length()) {
                        val d = qd.optString(j).trim()
                        if (d.isNotEmpty()) questionDrafts.add(d)
                    }
                }
                val completedSteps = LinkedHashSet<Int>()
                val cs = o.optJSONArray("completedSteps")
                if (cs != null) {
                    for (j in 0 until cs.length()) {
                        val idx = cs.optInt(j, -1)
                        if (idx in items.indices) completedSteps.add(idx)
                    }
                }
                val distinctOpen = openQuestions.distinct()
                loaded.add(
                    StoredNote(
                        id = o.optLong("id"),
                        title = o.optString("title"),
                        oneLine = o.optString("oneLine"),
                        mode = o.optString("mode", "Insight"),
                        whenText = o.optString("whenText"),
                        verbatim = o.optString("verbatim"),
                        why = o.optString("why"),
                        question = distinctOpen.firstOrNull() ?: "",
                        tags = tags,
                        audioPath = o.optString("audioPath").ifBlank { null },
                        spaceId = o.optString("spaceId").ifBlank { null },
                        // Files written before editing existed have no key at all; 0 is the
                        // on-disk spelling of "never edited", never a real timestamp.
                        editedAt = o.optLong("editedAt", 0L).takeIf { it > 0L },
                        // Every note written before formats existed is a regular note.
                        format = o.optString("format", NoteFormat.NOTE.id)
                            .takeIf { NoteFormat.entries.any { f -> f.id == it } }
                            ?: NoteFormat.NOTE.id,
                        items = items,
                        createdAt = o.optLong("createdAt", 0L),
                        completedAt = o.optLong("completedAt", 0L).takeIf { it > 0L },
                        followUps = followUps,
                        openQuestions = distinctOpen,
                        questionDrafts = questionDrafts.distinct(),
                        completedSteps = completedSteps
                    )
                )
            }
            loaded
        }

        parsed.onSuccess { loaded ->
            var migrated = false
            if (loaded.any { it.createdAt <= 0L }) {
                val base = loaded.filter { it.createdAt > 0L }.minOfOrNull { it.createdAt }?.minus(1000L)
                    ?: System.currentTimeMillis()
                for (i in loaded.indices) {
                    if (loaded[i].createdAt <= 0L) {
                        loaded[i] = loaded[i].copy(createdAt = (base - i * 1000L).coerceAtLeast(1L))
                        migrated = true
                    }
                }
            }
            notes.clear()
            notes.addAll(loaded)
            rebuildIndexes()
            ids.set(loaded.maxOfOrNull { it.id } ?: 0L)
            if (migrated) save()
        }.onFailure { e ->
            CaptureLog.add("notes: load failed - ${e.message}")
            quarantineUnreadable(f)
            notes.clear()
            rebuildIndexes()
            ids.set(0L)
        }
    }

    /** Never let an unreadable file be silently replaced by the next save's empty array. */
    private fun quarantineUnreadable(bad: File) {
        val target = File(bad.parentFile, bad.name + ".corrupt-" + System.currentTimeMillis())
        if (bad.renameTo(target)) {
            CaptureLog.add("notes: moved unreadable file to ${target.name}")
        } else {
            // No second copy exists: block writes rather than destroy the only data there is.
            writesBlocked = true
            CaptureLog.add("notes: could not move ${bad.name} aside, saving disabled")
        }
    }

    private fun save() {
        _version.value = _version.value + 1L
        val f = file ?: return
        if (writesBlocked) {
            CaptureLog.add("notes: save skipped, file was left unreadable")
            return
        }
        val snapshot = notes.toList()
        StoreIo.executor.execute {
            runCatching {
                val arr = JSONArray()
                snapshot.forEach { n ->
                    arr.put(
                        JSONObject().apply {
                            put("id", n.id)
                            put("title", n.title)
                            put("oneLine", n.oneLine)
                            put("mode", n.mode)
                            put("whenText", n.whenText)
                            put("verbatim", n.verbatim)
                            put("why", n.why)
                            put("question", n.question)
                            put("openQuestions", JSONArray(n.openQuestions))
                            if (n.questionDrafts.isNotEmpty()) {
                                put("questionDrafts", JSONArray(n.questionDrafts))
                            }
                            put("tags", JSONArray(n.tags))
                            put("audioPath", n.audioPath ?: "")
                            put("spaceId", n.spaceId ?: "")
                            // 0 rather than JSON null: keeps the field numeric for every reader.
                            put("editedAt", n.editedAt ?: 0L)
                            put("format", n.format)
                            put("items", JSONArray(n.items))
                            if (n.completedSteps.isNotEmpty()) {
                                put("completedSteps", JSONArray(n.completedSteps.sorted()))
                            }
                            put("createdAt", n.createdAt)
                            put("completedAt", n.completedAt ?: 0L)
                            if (n.followUps.isNotEmpty()) {
                                val fa = JSONArray()
                                n.followUps.forEach { fu ->
                                    fa.put(
                                        JSONObject().apply {
                                            put("text", fu.text)
                                            put("whenText", fu.whenText)
                                            put("createdAt", fu.createdAt)
                                            put("audioPath", fu.audioPath ?: "")
                                        }
                                    )
                                }
                                put("followUps", fa)
                            }
                        }
                    )
                }
                StoreIo.writeAtomic(f, arr.toString())
            }.onFailure { CaptureLog.add("notes: save failed - ${it.message}") }
        }
    }
}
